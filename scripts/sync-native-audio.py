#!/usr/bin/env python3
"""Export the authored native audio catalog, focus routing and recordings."""
import json, re, shutil, subprocess, sys, tempfile
from pathlib import Path
web = Path(__file__).resolve().parents[1]
native = Path(sys.argv[1]) if len(sys.argv) > 1 else web.parent / 'PelvicFloor' / 'Pelvic Floor'
source = (native / 'Core/Audio/AudioSessionCatalog.swift').read_text()
quoted = r'"(?:[^"\\]|\\.)*"'
sessions = []
pattern = re.compile(r'session\(("[^"\n]+"), goal: \.(\w+), title: ('+quoted+r'), subtitle: ('+quoted+r'), icon: ('+quoted+r')(?:, seconds: (\d+))?, beats: \[(.*?)\n        \]\)',re.S)
beat_pattern = re.compile(r'\(('+quoted+r'), ('+quoted+r'), ('+quoted+r'), ('+quoted+r'), \.(\w+)\)')
for match in pattern.finditer(source):
    sid, goal, title, subtitle, icon, seconds, body = match.groups()
    session = dict(id=json.loads(sid),goal=goal,title=json.loads(title),subtitle=json.loads(subtitle),icon=json.loads(icon),beats=[],continuousTrackID='audio_track_'+json.loads(sid))
    for beat in beat_pattern.finditer(body):
        bid, spoken, label, detail, phase = beat.groups()
        session['beats'].append(dict(id=json.loads(bid),spoken=json.loads(spoken),label=json.loads(label),detail=json.loads(detail),phase=phase,duration=int(seconds or 42)))
    assert session['beats'],session['id']
    sessions.append(session)
assert len(sessions)==50, f'Expected 50 authored sessions, got {len(sessions)}'
for session in list(sessions):
    if session['goal']=='coreStrength':
        sessions.append({**session,'id':'stability_'+session['id'],'goal':'stability'})
focus_source=(native/'Core/GoalFocus.swift').read_text()
focus_ids=dict(re.findall(r'static let (\w+) = Self\(rawValue: "([^"]+)"\)',focus_source))
focus_map={}
for condition,sid in re.findall(r'if (focusID.*?) \{ return "([^"]+)" \}',source):
    for name in re.findall(r'focusID == \.(\w+)',condition):
        focus_map[focus_ids[name]]=sid
cue_source=(native/'Core/Sessions/SessionScripts.swift').read_text()
cues={json.loads(text):sid for sid,text in re.findall(r'SessionCue\("([^"]+)", ('+quoted+r')\)',cue_source)}
for i in range(1,21):cues[f'{i}.']=f'count_{i}'
assets=native/'Core/Sessions/VoiceClips'
for asset in assets.glob('*.mp3'):shutil.copy2(asset,web/'public/audio'/asset.name)
available={p.stem for p in (web/'public/audio').glob('*.mp3')}
for session in sessions:assert session['continuousTrackID'] in available,session['id']
cues={text:sid for text,sid in cues.items() if sid in available}
data={'sessions':sessions,'focusSessions':focus_map,'cueClips':cues,'assets':sorted(available)}
(web/'lib/audioCatalogData.js').write_text('// Generated by scripts/sync-native-audio.py. Edit the native catalog, then regenerate.\nexport const AUDIO_CATALOG_DATA = '+json.dumps(data,ensure_ascii=False,indent=2)+';\n')
print(f'Exported {len(sessions)} sessions, {len(focus_map)} focus routes, {len(available)} recordings.')

# Execute the Swift script builders rather than duplicating their pacing rules.
# This captures every release cue, count, rest and duration exactly.
swift_export = r'''
import Foundation
func encode(_ script: SessionScript) -> [String: Any] {
    ["id": script.id, "title": script.title, "subtitle": script.subtitle,
     "totalDuration": script.totalDuration, "repTotal": script.repTotal,
     "stepOffsets": script.stepOffsets,
     "steps": script.steps.map { step -> [String: Any] in
         ["id": step.id, "phase": step.phase.rawValue, "duration": step.duration,
          "label": step.label, "detail": step.detail, "countsAloud": step.countsAloud,
          "rep": step.rep.map { $0 as Any } ?? NSNull(),
          "cues": step.cues.map { cue -> [String: Any] in
              ["text": cue.text, "clipID": cue.clipID.map { $0 as Any } ?? NSNull(), "at": cue.delay]
          }]
     }]
}
let output: [String: Any] = [
    "urgeModes": UrgeRescueMode.allCases.map { mode -> [String: Any] in
        ["id": mode.rawValue, "title": mode.title, "tagline": mode.tagline, "script": encode(mode.script)]
    },
    "kegelSets": KegelSet.pickerOrder.map { set -> [String: Any] in
        ["id": set.rawValue, "title": set.title, "blurb": set.blurb, "script": encode(set.script)]
    }
]
let data = try JSONSerialization.data(withJSONObject: output, options: [.sortedKeys])
FileHandle.standardOutput.write(data)
'''
with tempfile.TemporaryDirectory(prefix='pelvi-audio-export-') as directory:
    main=Path(directory)/'main.swift'; binary=Path(directory)/'export'
    main.write_text(swift_export)
    subprocess.run(['swiftc',str(native/'Core/Sessions/SessionScripts.swift'),str(main),'-o',str(binary)],check=True)
    scripts=json.loads(subprocess.check_output([str(binary)]))
    (web/'lib/sessionScriptData.js').write_text('// Generated from native SessionScripts.swift by scripts/sync-native-audio.py.\nexport const SESSION_SCRIPT_DATA = '+json.dumps(scripts,ensure_ascii=False,indent=2)+';\n')
print('Exported the native Urge Rescue and Kegel script builders.')
